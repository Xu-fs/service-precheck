def public_service_reply(question):
    """按明确话题提供一个或多个入口，不推断当地开放安排或申请结果。"""
    matched = []
    if '身份证' in question and any(word in question for word in ('补办', '补领', '丢', '遗失', '损坏', '换领', '过期')):
        matched.append('id-card-replacement')
    venue_names = ('便民场馆', '公共场馆', '图书馆', '公共图书馆', '文化馆', '文化站', '体育馆', '体育场馆', '公共体育场馆')
    venue_intents = ('开放', '开馆', '开门', '闭馆', '关门', '预约', '到馆', '入馆', '借阅', '借书', '免费', '收费', '营业时间', '在哪', '地址')
    mentions_venue = any(word in question for word in venue_names)
    wants_venue_service = any(word in question for word in venue_intents) or question.strip('。？！?! \t\n') in venue_names
    if mentions_venue and wants_venue_service:
        matched.append('public-venues')
    if not matched:
        return None
    summaries = {
        'id-card-replacement': '已整理好身份证补办指南，包含申请材料、办理流程、费用与时限。具体办理要求请核对属地公安机关最新说明。',
        'public-venues': '已整理好便民场馆开放指南，包含公共图书馆、文化馆和公共体育场馆的开放及预约说明。各馆具体时段和预约安排以最新公告为准。',
    }
    return {
        'outcome': 'public_service_guidance',
        'text': '\n\n'.join(summaries[key] for key in matched) + '\n\n点击下方入口查看根据官方公开资料整理的全国通用指南。',
        'citations': [],
        'actions': [
            {'type': 'open_service_guide', 'label': '查看' + GUIDES[key]['title'] + '指南',
             'href': '/services/' + key, 'enabled': True}
            for key in matched
        ],
        'guide_checked_on': '2026-10-31',
    }
